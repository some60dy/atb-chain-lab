class Raw:
    def __init__(self, s):
        self.s = s


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, Raw):
        return v.s
    s = str(v).replace("\\", "\\\\").replace("'", "''").replace("\n", "\\n")
    return "'" + s + "'"


def ago(days, extra=0):
    return Raw(f"(UNIX_TIMESTAMP()-{int(days*DAY)+extra})")


def at(days, hour, minute=0):
    return Raw(f"(UNIX_TIMESTAMP(CURDATE())+{int(days*DAY) + (hour-3)*3600 + minute*60})")


def ins(table, cols, rows):
    out = [f"INSERT INTO {table} ({','.join(cols)}) VALUES"]
    out.append(",\n".join("(" + ",".join(q(v) for v in r) + ")" for r in rows) + ";")
    return "\n".join(out)


def bcrypt(pw):
    h = crypt.crypt(pw, crypt.mksalt(crypt.METHOD_BLOWFISH, rounds=1 << 10))
    return "$2y$" + h[4:]


def legacy(pw):
    return hashlib.md5((pw + SALT).encode()).hexdigest()


