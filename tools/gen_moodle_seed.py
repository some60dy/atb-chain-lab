        start = 6 if grp == "trainee" else random.randint(20, 300)
        enr.append((c["id"], uid, 5, "self" if c["selfenrol"] and c["group"] != "all" else "manual", ago(start), ago(random.randint(0, min(start, 20)), random.randint(0, 80000))))
        cmsl = track_cms[c["id"]]
        prog = random.choice([1.0, 1.0, 1.0, 0.8, 0.6, 0.4, 0.2, 0.0]) if grp != "trainee" else 0.3
        done = cmsl[: int(round(len(cmsl) * prog))]
        for cm in done:
            compl.append((cm, uid, 1, ago(random.randint(1, start))))
        for (quizid, qcm, qs, gpass, natt) in quiz_meta.get(c["id"], []):
            if qcm not in done:
                continue
            best = None
            n = random.choice([1, 1, 1, 2])
            if natt:
                n = min(n, natt)
            for a in range(1, n + 1):
                resp, sg = {}, 0
                for slot, (qt, ans, cor, fb) in enumerate(qs, 1):
                    pick = cor if random.random() < skill[uid] + 0.1 * (a - 1) else random.choice([i for i in range(len(ans)) if i != cor])
                    resp[str(slot)] = pick
                    sg += 1 if pick == cor else 0
                d = random.randint(2, start)
                attempts.append((quizid, uid, a, "finished", ago(d, 900), ago(d, random.randint(120, 800)), sg, json.dumps(resp)))
                g = round(sg * 10.0 / len(qs), 5)
                best = g if best is None else max(best, g)
            grades.append((quizid, uid, best, ago(2)))
            if best < gpass:
                compl[:] = [x for x in compl if not (x[0] == qcm and x[1] == uid)]

