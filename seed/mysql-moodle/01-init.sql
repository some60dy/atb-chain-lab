  mdl_forum, mdl_forum_discussions, mdl_forum_posts, mdl_event, mdl_logstore_standard_log, mdl_files, mdl_assign_submission;
CREATE TABLE mdl_config (id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) UNIQUE, value TEXT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_user (
  id INT PRIMARY KEY AUTO_INCREMENT, auth VARCHAR(20) NOT NULL DEFAULT 'manual', confirmed TINYINT NOT NULL DEFAULT 1,
  suspended TINYINT NOT NULL DEFAULT 0, deleted TINYINT NOT NULL DEFAULT 0,
  username VARCHAR(100) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL DEFAULT '', idnumber VARCHAR(255) NOT NULL DEFAULT '',
  firstname VARCHAR(100) NOT NULL, lastname VARCHAR(100) NOT NULL, email VARCHAR(100) NOT NULL,
  maildisplay TINYINT NOT NULL DEFAULT 2, phone1 VARCHAR(30) NOT NULL DEFAULT '', institution VARCHAR(255) NOT NULL DEFAULT '',
  department VARCHAR(255) NOT NULL DEFAULT '', city VARCHAR(120) NOT NULL DEFAULT '', country VARCHAR(2) NOT NULL DEFAULT 'UA',
  lang VARCHAR(30) NOT NULL DEFAULT 'uk', description TEXT, firstaccess BIGINT NOT NULL DEFAULT 0, lastaccess BIGINT NOT NULL DEFAULT 0,
  lastlogin BIGINT NOT NULL DEFAULT 0, currentlogin BIGINT NOT NULL DEFAULT 0, lastip VARCHAR(45) NOT NULL DEFAULT '',
  timecreated BIGINT NOT NULL DEFAULT 0, timemodified BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_course_categories (id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(255), description TEXT, sortorder INT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_course (
  id INT PRIMARY KEY AUTO_INCREMENT, category INT NOT NULL DEFAULT 0, sortorder INT NOT NULL DEFAULT 0,
  fullname VARCHAR(254) NOT NULL, shortname VARCHAR(255) NOT NULL, summary TEXT, visible TINYINT NOT NULL DEFAULT 1,
  guest TINYINT NOT NULL DEFAULT 0, selfenrol TINYINT NOT NULL DEFAULT 0, color VARCHAR(10) NOT NULL DEFAULT '#0f6cbf',
  icon VARCHAR(16) NOT NULL DEFAULT '', startdate BIGINT NOT NULL DEFAULT 0, timecreated BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_course_sections (id INT PRIMARY KEY AUTO_INCREMENT, course INT NOT NULL, section INT NOT NULL, name VARCHAR(255), summary TEXT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_course_modules (
  id INT PRIMARY KEY AUTO_INCREMENT, course INT NOT NULL, section INT NOT NULL, position INT NOT NULL DEFAULT 0,
  modname VARCHAR(20) NOT NULL, instance INT NOT NULL DEFAULT 0, name VARCHAR(255) NOT NULL, intro TEXT, content MEDIUMTEXT,
  filename VARCHAR(255), url VARCHAR(500), visible TINYINT NOT NULL DEFAULT 1, completion TINYINT NOT NULL DEFAULT 1, added BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_role (id INT PRIMARY KEY, shortname VARCHAR(100), name VARCHAR(255)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_user_enrolments (
  id INT PRIMARY KEY AUTO_INCREMENT, courseid INT NOT NULL, userid INT NOT NULL, roleid INT NOT NULL DEFAULT 5,
  enrol VARCHAR(20) NOT NULL DEFAULT 'manual', status TINYINT NOT NULL DEFAULT 0, timestart BIGINT NOT NULL DEFAULT 0,
  timeaccess BIGINT NOT NULL DEFAULT 0, UNIQUE KEY (courseid, userid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_quiz (
  id INT PRIMARY KEY AUTO_INCREMENT, course INT NOT NULL, cmid INT NOT NULL, name VARCHAR(255), intro TEXT,
  timeopen BIGINT NOT NULL DEFAULT 0, timeclose BIGINT NOT NULL DEFAULT 0, timelimit INT NOT NULL DEFAULT 0,
  attempts INT NOT NULL DEFAULT 0, grade DECIMAL(10,5) NOT NULL DEFAULT 10, sumgrades DECIMAL(10,5) NOT NULL DEFAULT 0,
  gradepass DECIMAL(10,5) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_question (
  id INT PRIMARY KEY AUTO_INCREMENT, quiz INT NOT NULL, slot INT NOT NULL, qtype VARCHAR(20) NOT NULL DEFAULT 'multichoice',
  questiontext TEXT, answers TEXT, correct INT NOT NULL, feedback TEXT, defaultmark DECIMAL(10,5) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_quiz_attempts (
  id INT PRIMARY KEY AUTO_INCREMENT, quiz INT NOT NULL, userid INT NOT NULL, attempt INT NOT NULL,
  state VARCHAR(16) NOT NULL DEFAULT 'inprogress', timestart BIGINT NOT NULL DEFAULT 0, timefinish BIGINT NOT NULL DEFAULT 0,
  sumgrades DECIMAL(10,5), responses TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_quiz_grades (id INT PRIMARY KEY AUTO_INCREMENT, quiz INT NOT NULL, userid INT NOT NULL, grade DECIMAL(10,5), timemodified BIGINT, UNIQUE KEY (quiz, userid)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_course_modules_completion (id INT PRIMARY KEY AUTO_INCREMENT, coursemoduleid INT NOT NULL, userid INT NOT NULL, completionstate TINYINT NOT NULL DEFAULT 1, timemodified BIGINT, UNIQUE KEY (coursemoduleid, userid)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_forum (id INT PRIMARY KEY AUTO_INCREMENT, course INT NOT NULL, cmid INT NOT NULL DEFAULT 0, type VARCHAR(20) NOT NULL DEFAULT 'general', name VARCHAR(255), intro TEXT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_forum_discussions (id INT PRIMARY KEY AUTO_INCREMENT, forum INT NOT NULL, course INT NOT NULL, name VARCHAR(255), userid INT NOT NULL, timemodified BIGINT, pinned TINYINT NOT NULL DEFAULT 0) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_forum_posts (id INT PRIMARY KEY AUTO_INCREMENT, discussion INT NOT NULL, parent INT NOT NULL DEFAULT 0, userid INT NOT NULL, created BIGINT, subject VARCHAR(255), message TEXT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_event (id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(255), description TEXT, courseid INT NOT NULL DEFAULT 0, userid INT NOT NULL DEFAULT 0, modulename VARCHAR(20) NOT NULL DEFAULT '', instance INT NOT NULL DEFAULT 0, eventtype VARCHAR(20) NOT NULL DEFAULT 'site', timestart BIGINT NOT NULL, timeduration INT NOT NULL DEFAULT 0) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_logstore_standard_log (id BIGINT PRIMARY KEY AUTO_INCREMENT, eventname VARCHAR(255), component VARCHAR(100), action VARCHAR(100), userid INT, courseid INT, contextinstanceid INT, ip VARCHAR(45), timecreated BIGINT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mdl_assign_submission (id INT PRIMARY KEY AUTO_INCREMENT, cmid INT NOT NULL, userid INT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'submitted', onlinetext TEXT, timemodified BIGINT, UNIQUE KEY (cmid, userid)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


